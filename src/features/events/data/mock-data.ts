/**
 * Dates are generated relative to today so the agenda never looks stale.
 *
 * They snap to a weekend, because verzamelbeurzen are weekend events. A plain
 * day offset would land every fair on whatever weekday today happens to be,
 * and a Monday card fair reads as obviously invented.
 */
function weekendDate(
  weeksAhead: number,
  day: 'saturday' | 'sunday' = 'saturday',
): string {
  const date = new Date();
  date.setHours(12, 0, 0, 0);
  const target = day === 'saturday' ? 6 : 0;
  let delta = (target - date.getDay() + 7) % 7;
  // Never today: an event happening right now has no page worth visiting.
  if (delta === 0) delta = 7;
  date.setDate(date.getDate() + delta + weeksAhead * 7);
  return date.toISOString().slice(0, 10);
}

/** The Sunday of a weekend that starts on the given Saturday. */
function dayAfter(iso: string): string {
  const date = new Date(`${iso}T12:00:00`);
  date.setDate(date.getDate() + 1);
  return date.toISOString().slice(0, 10);
}

